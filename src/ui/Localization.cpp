QString languageCode() {
    const auto code = QSettings().value("ui/language", "zh_CN").toString();
    return code.startsWith("en", Qt::CaseInsensitive) ? "en_US" : "zh_CN";
}

bool isEnglish() { return languageCode() == "en_US"; }

void setLanguageCode(const QString& code) {
    QSettings settings;
    settings.setValue("ui/language", code.startsWith("en", Qt::CaseInsensitive) ? "en_US" : "zh_CN");
    settings.sync();
}

QString text(const QString& source) {
    if (!isEnglish() || source.isEmpty())
        return source;
    const auto found = english().constFind(source);
    if (found != english().cend())
        return found.value();
    const QList<QPair<QString, QString>> prefixes{
        {"设备已连接 · ", "Device connected · "}, {"正在建立通信 · ", "Connecting · "},
        {"通信建立成功 · ", "Communication established · "},
        {"通信建立失败 · ", "Communication failed · "},
        {"通信中断 · ", "Communication lost · "},
        {"电机使能失败 · 错误码 ", "Failed to enable motor · error code "},
        {"固件文件长度 ", "Firmware size "}, {"无法创建保存目录：", "Unable to create record folder: "},
        {"电机参数已写入设备", "Motor parameters written to device"}, {"保护参数已写入设备", "Protection parameters written to device"},
        {"电机参数已应用", "Motor parameters applied"}, {"保护参数已应用", "Protection parameters applied"}
    };
    for (const auto& prefix : prefixes)
        if (source.startsWith(prefix.first))
            return prefix.second + source.mid(prefix.first.size());
    return source;
}
